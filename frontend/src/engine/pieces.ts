/**
 * SRS 벽 차기 표. 키 "from>to", 값은 [dx, dy] 목록이고 dy는 위쪽이 + 다(SRS 원표 표기).
 * 보드 행 번호는 아래로 커지므로 적용할 때 row -= dy 로 쓴다. shared/rules-fixtures/srs-kicks.json과 같아야 한다.
 */
export type KickTable = Record<string, readonly (readonly [number, number])[]>;

export const KICKS_JLSTZ: KickTable = {
  '0>1': [[0, 0], [-1, 0], [-1, 1], [0, -2], [-1, -2]],
  '1>0': [[0, 0], [1, 0], [1, -1], [0, 2], [1, 2]],
  '1>2': [[0, 0], [1, 0], [1, -1], [0, 2], [1, 2]],
  '2>1': [[0, 0], [-1, 0], [-1, 1], [0, -2], [-1, -2]],
  '2>3': [[0, 0], [1, 0], [1, 1], [0, -2], [1, -2]],
  '3>2': [[0, 0], [-1, 0], [-1, -1], [0, 2], [-1, 2]],
  '3>0': [[0, 0], [-1, 0], [-1, -1], [0, 2], [-1, 2]],
  '0>3': [[0, 0], [1, 0], [1, 1], [0, -2], [1, -2]],
};

export const KICKS_I: KickTable = {
  '0>1': [[0, 0], [-2, 0], [1, 0], [-2, -1], [1, 2]],
  '1>0': [[0, 0], [2, 0], [-1, 0], [2, 1], [-1, -2]],
  '1>2': [[0, 0], [-1, 0], [2, 0], [-1, 2], [2, -1]],
  '2>1': [[0, 0], [1, 0], [-2, 0], [1, -2], [-2, 1]],
  '2>3': [[0, 0], [2, 0], [-1, 0], [2, 1], [-1, -2]],
  '3>2': [[0, 0], [-2, 0], [1, 0], [-2, -1], [1, 2]],
  '3>0': [[0, 0], [1, 0], [-2, 0], [1, -2], [-2, 1]],
  '0>3': [[0, 0], [-1, 0], [2, 0], [-1, 2], [2, -1]],
};

export function kicksFor(piece: PieceType, from: Rotation, to: Rotation): readonly (readonly [number, number])[] {
  if (piece === 'O') return [[0, 0]];
  return (piece === 'I' ? KICKS_I : KICKS_JLSTZ)[`${from}>${to}`] ?? [];
}

export function cellsOf(piece: PieceType, rotation: Rotation, x: number, y: number): [number, number][] {
  return SHAPES[piece][rotation].map(([r, c]) => [y + r, x + c]);
}
